"""Tests for build_parquet.py.

The one that matters most is `test_default_matches_upstream`: it runs the ORIGINAL script
(recovered from git) and the current one over identical synthetic protobufs and requires the
parquet output to be identical. Every behaviour change in this PR is opt-in, and that claim is
worth checking rather than asserting -- the published dataset is generated by this script.

Synthetic input is used deliberately: the fixtures cover the awkward cases (a card whose
reviews reorder under the show-time correction, a clamped duration, relearning sequences)
which a sample of real users may or may not contain.

Run:  python -m pytest test_build_parquet.py -q
      python test_build_parquet.py          # same checks, no pytest needed
"""

import subprocess
import sys
import tempfile
from pathlib import Path

import pandas as pd
import pyarrow.parquet as pq

import build_parquet as bp
from stats_pb2 import CardEntry, Dataset, DeckEntry, RevlogEntry

HERE = Path(__file__).resolve().parent
# Anki ids are creation timestamps in epoch ms; these are realistic magnitudes (~2021).
BASE = 1_621_696_450_781
DAY = 86_400_000


def _revlog(rid, cid, button, kind, taken):
    e = RevlogEntry()
    e.id, e.cid, e.button_chosen, e.review_kind, e.taken_millis = rid, cid, button, kind, taken
    e.ease_factor = 2500
    return e


def make_dataset():
    """Three cards, protobuf order grouped per card, covering the cases that matter."""
    ds = Dataset()
    ds.next_day_at = (BASE // 1000) + 4 * 3600

    # card A: a normal learn -> review sequence.
    a = BASE
    ds.revlogs.extend([
        _revlog(a + 0 * DAY, a, 3, 0, 5_000),
        _revlog(a + 1 * DAY, a, 3, 1, 8_000),
        _revlog(a + 5 * DAY, a, 2, 1, 12_000),
    ])
    # card B: two reviews only 30 s apart, the SECOND taking 58 s. Under --show-time the
    # second review's show time lands BEFORE the first's, which is the negative-gap case.
    b = BASE + 1000
    ds.revlogs.extend([
        _revlog(b + 0 * DAY, b, 3, 0, 3_000),
        _revlog(b + 0 * DAY + 30_000, b, 1, 2, 58_000),
    ])
    # card C: a clamped duration (exactly 60 s) plus a lapse -> relearning.
    c = BASE + 2000
    ds.revlogs.extend([
        _revlog(c + 0 * DAY, c, 3, 0, 60_000),
        _revlog(c + 2 * DAY, c, 1, 1, 60_000),
        _revlog(c + 2 * DAY + 600_000, c, 3, 2, 4_000),
    ])

    for cid, nid, did in ((a, a + 7, BASE + 50), (b, b + 7, BASE + 50), (c, c + 7, BASE + 60)):
        ce = CardEntry()
        ce.id, ce.note_id, ce.deck_id = cid, nid, did
        ds.cards.append(ce)
    for did, pid in ((BASE + 50, 0), (BASE + 60, BASE + 50)):
        de = DeckEntry()
        de.id, de.parent_id, de.preset_id = did, pid, BASE + 90
        ds.decks.append(de)
    return ds


def write_input(tmp: Path, user_id: int = 70):
    d = tmp / "revlogs"
    d.mkdir(parents=True, exist_ok=True)
    (d / f"{user_id}.revlog").write_bytes(make_dataset().SerializeToString())
    return d


def read_table(out: Path, name: str, user_id: int = 70):
    p = out / name / f"user_id={user_id}" / "data.parquet"
    return pq.read_table(p).to_pandas() if p.exists() else None


def build(tmp: Path, argv):
    inp, out = write_input(tmp), tmp / "out"
    bp.main([*argv, "--revlogs-dir", str(inp), "--output-dir", str(out), "--workers", "1"])
    return out


