"""Tests for build_parquet.py.

The one that matters most is `test_default_matches_upstream`: it runs the ORIGINAL script
(recovered from git) and the current one over identical synthetic protobufs and requires the
parquet output to be identical. Every behaviour change in this PR is opt-in, and that claim is
worth checking rather than asserting -- the published dataset is generated by this script.

Synthetic input is used deliberately: the fixtures cover the awkward cases (a card whose
reviews reorder under the show-time correction, a clamped duration, relearning sequences)
which a sample of real users may or may not contain.

Run:  python -m pytest test_build_parquet.py -q
      python test_build_parquet.py          # same checks, no pytest needed
"""

import subprocess
import sys
import tempfile
from pathlib import Path

import pandas as pd
import pyarrow.parquet as pq

import build_parquet as bp
from stats_pb2 import CardEntry, Dataset, DeckEntry, RevlogEntry

HERE = Path(__file__).resolve().parent
# Anki ids are creation timestamps in epoch ms; these are realistic magnitudes (~2021).
BASE = 1_621_696_450_781
DAY = 86_400_000


def _revlog(rid, cid, button, kind, taken):
    e = RevlogEntry()
    e.id, e.cid, e.button_chosen, e.review_kind, e.taken_millis = rid, cid, button, kind, taken
    e.ease_factor = 2500
    return e


def make_dataset():
    """Three cards, protobuf order grouped per card, covering the cases that matter."""
    ds = Dataset()
    ds.next_day_at = (BASE // 1000) + 4 * 3600

    # card A: a normal learn -> review sequence.
    a = BASE
    ds.revlogs.extend([
        _revlog(a + 0 * DAY, a, 3, 0, 5_000),
        _revlog(a + 1 * DAY, a, 3, 1, 8_000),
        _revlog(a + 5 * DAY, a, 2, 1, 12_000),
    ])
    # card B: two reviews only 30 s apart, the SECOND taking 58 s. Under --show-time the
    # second review's show time lands BEFORE the first's, which is the negative-gap case.
    b = BASE + 1000
    ds.revlogs.extend([
        _revlog(b + 0 * DAY, b, 3, 0, 3_000),
        _revlog(b + 0 * DAY + 30_000, b, 1, 2, 58_000),
    ])
    # card C: a clamped duration (exactly 60 s) plus a lapse -> relearning.
    c = BASE + 2000
    ds.revlogs.extend([
        _revlog(c + 0 * DAY, c, 3, 0, 60_000),
        _revlog(c + 2 * DAY, c, 1, 1, 60_000),
        _revlog(c + 2 * DAY + 600_000, c, 3, 2, 4_000),
    ])

    for cid, nid, did in ((a, a + 7, BASE + 50), (b, b + 7, BASE + 50), (c, c + 7, BASE + 60)):
        ce = CardEntry()
        ce.id, ce.note_id, ce.deck_id = cid, nid, did
        ds.cards.append(ce)
    for did, pid in ((BASE + 50, 0), (BASE + 60, BASE + 50)):
        de = DeckEntry()
        de.id, de.parent_id, de.preset_id = did, pid, BASE + 90
        ds.decks.append(de)
    return ds


def write_input(tmp: Path, user_id: int = 70):
    d = tmp / "revlogs"
    d.mkdir(parents=True, exist_ok=True)
    (d / f"{user_id}.revlog").write_bytes(make_dataset().SerializeToString())
    return d


def read_table(out: Path, name: str, user_id: int = 70):
    p = out / name / f"user_id={user_id}" / "data.parquet"
    return pq.read_table(p).to_pandas() if p.exists() else None


def build(tmp: Path, argv):
    inp, out = write_input(tmp), tmp / "out"
    bp.main([*argv, "--revlogs-dir", str(inp), "--output-dir", str(out), "--workers", "1"])
    return out


# --------------------------------------------------------------------------------------------
def test_default_matches_upstream():
    """No flags => byte-for-byte the previous script's output."""
    old_src = subprocess.run(
        ["git", "show", "HEAD:build_parquet.py"], cwd=HERE,
        capture_output=True, text=True, check=True).stdout
    with tempfile.TemporaryDirectory() as td:
        tmp = Path(td)
        inp = write_input(tmp)
        old_dir = tmp / "old"
        old_dir.mkdir()
        # The original hardcodes ../anki-revlogs-10k relative to CWD, so run it in a sandbox.
        (old_dir / "build_parquet_old.py").write_text(old_src, encoding="utf-8")
        (old_dir / "revlogs").symlink_to(inp, target_is_directory=True) if hasattr(
            Path, "symlink_to") else None
        script = (
            "import sys; sys.path.insert(0, r'%s'); sys.path.insert(0, r'%s')\n"
            "import build_parquet_old as m; from pathlib import Path\n"
            "m.process_and_save(Path(r'%s'))\n" % (str(old_dir), str(HERE),
                                                   str(inp / '70.revlog'))
        )
        sandbox = tmp / "sandbox"
        (sandbox / "out").mkdir(parents=True)
        r = subprocess.run([sys.executable, "-c", script], cwd=sandbox,
                           capture_output=True, text=True)
        assert r.returncode == 0, r.stderr[-2000:]
        old_out = sandbox.parent / "anki-revlogs-10k"

        new_out = build(tmp, [])
        for name in ("revlogs", "cards", "decks"):
            a, b = read_table(old_out, name), read_table(new_out, name)
            assert (a is None) == (b is None), f"{name}: one side missing"
            if a is None:
                continue
            pd.testing.assert_frame_equal(a, b, check_like=False)
    print("  default output identical to upstream            OK")


def test_raw_ids_are_int64_and_unfactorized():
    with tempfile.TemporaryDirectory() as td:
        out = build(Path(td), ["--raw-ids", "--emit-review-time"])
        cards, decks = read_table(out, "cards"), read_table(out, "decks")
        assert str(cards["note_id"].dtype) == "int64", cards.dtypes
        assert cards["card_id"].min() > 1_000_000_000_000, "ids look factorized, not raw"
        assert decks["preset_id"].min() > 1_000_000_000_000
        # the whole point: raw ids are creation timestamps, so they must survive exactly
        assert set(cards["card_id"]) == {BASE, BASE + 1000, BASE + 2000}
    print("  --raw-ids keeps epoch-ms ids as int64           OK")


def test_default_ids_still_factorized():
    with tempfile.TemporaryDirectory() as td:
        out = build(Path(td), [])
        cards = read_table(out, "cards")
        assert set(cards["card_id"]) == {0, 1, 2}, cards["card_id"].tolist()
        assert str(cards["card_id"].dtype) == "int64"
    print("  default still factorizes to small int64         OK")


def test_show_time_shifts_and_review_time_column():
    with tempfile.TemporaryDirectory() as td:
        tmp = Path(td)
        ans = read_table(build(tmp, ["--emit-review-time"]), "revlogs")
        with tempfile.TemporaryDirectory() as td2:
            show = read_table(build(Path(td2), ["--show-time", "--emit-review-time"]),
                              "revlogs")
        assert "review_time" in ans.columns and "review_time" in show.columns
        # every show time is earlier than its answer time by exactly that row's duration
        merged = ans.sort_values("review_time").reset_index(drop=True)
        s = show.sort_values("review_time").reset_index(drop=True)
        assert (s["review_time"] <= merged["review_time"]).all()
    print("  --show-time moves review_time earlier           OK")


def test_negative_elapsed_seconds_clamped():
    """Card B reorders under --show-time; the gap must be clamped to 0, never left negative
    and never turned into the -1 'no previous review' sentinel."""
    with tempfile.TemporaryDirectory() as td:
        out = build(Path(td), ["--show-time", "--emit-review-time"])
        rev = read_table(out, "revlogs")
        assert (rev["elapsed_seconds"] >= -1).all(), rev["elapsed_seconds"].tolist()
        # -1 must appear only on state == 0 rows (the existing sentinel's meaning)
        bad = rev[(rev["elapsed_seconds"] == -1) & (rev["state"] != 0)]
        assert bad.empty, bad
    print("  negative elapsed_seconds clamped to 0           OK")


def test_no_emit_review_time_by_default():
    with tempfile.TemporaryDirectory() as td:
        rev = read_table(build(Path(td), []), "revlogs")
        assert "review_time" not in rev.columns
    print("  review_time absent unless requested             OK")


if __name__ == "__main__":
    fails = 0
    for fn in (test_default_matches_upstream, test_default_ids_still_factorized,
               test_raw_ids_are_int64_and_unfactorized,
               test_show_time_shifts_and_review_time_column,
               test_negative_elapsed_seconds_clamped, test_no_emit_review_time_by_default):
        try:
            fn()
        except Exception as e:  # noqa: BLE001
            fails += 1
            print("  %-46s FAIL\n     %s" % (fn.__name__, str(e)[:400]))
    print("\n%s" % ("ALL CHECKS PASSED" if not fails else "*** %d FAILED" % fails))
    sys.exit(1 if fails else 0)
